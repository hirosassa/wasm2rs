/// `(load helper, result type, memarg)` of an atomic load.
pub(super) fn atomic_load_kind(op: &Operator<'_>) -> Option<(Helper, ValType, MemArg)> {
    Some(match *op {
        Operator::I32AtomicLoad { memarg } => (Helper::LoadI32, ValType::I32, memarg),
        Operator::I32AtomicLoad8U { memarg } => (Helper::Load8U, ValType::I32, memarg),
        Operator::I32AtomicLoad16U { memarg } => (Helper::Load16U, ValType::I32, memarg),
        Operator::I64AtomicLoad { memarg } => (Helper::LoadI64, ValType::I64, memarg),
        Operator::I64AtomicLoad8U { memarg } => (Helper::Load8UI64, ValType::I64, memarg),
        Operator::I64AtomicLoad16U { memarg } => (Helper::Load16UI64, ValType::I64, memarg),
        Operator::I64AtomicLoad32U { memarg } => (Helper::Load32UI64, ValType::I64, memarg),
        _ => return None,
    })
}

/// `(store helper, memarg)` of an atomic store.
pub(super) fn atomic_store_kind(op: &Operator<'_>) -> Option<(Helper, MemArg)> {
    Some(match *op {
        Operator::I32AtomicStore { memarg } => (Helper::StoreI32, memarg),
        Operator::I32AtomicStore8 { memarg } => (Helper::Store8, memarg),
        Operator::I32AtomicStore16 { memarg } => (Helper::Store16, memarg),
        Operator::I64AtomicStore { memarg } => (Helper::StoreI64, memarg),
        Operator::I64AtomicStore8 { memarg } => (Helper::Store8I64, memarg),
        Operator::I64AtomicStore16 { memarg } => (Helper::Store16I64, memarg),
        Operator::I64AtomicStore32 { memarg } => (Helper::Store32I64, memarg),
        _ => return None,
    })
}

