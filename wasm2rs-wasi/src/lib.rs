//! The typed WASI 0.2.0 host for programs transpiled by wasm2rs.
//!
//! [`Host`] declares every method of the WASI 0.2.0 surface; a method a host does not
//! override traps (panics, naming the method), so one implementation always compiles and an
//! unsupported interface fails at the call instead of at build time.

// The hardening gates (rust-hardening) for this crate's hand-written code; the shared ones
// live in `[workspace.lints]`. Traps are raised through `host::slab::trap`, or by an `assert!` on a guest contract (check-write limits, empty poll list).
#![deny(
    clippy::panic,
    clippy::unwrap_in_result,
    clippy::cast_possible_truncation,
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::unreachable,
    clippy::indexing_slicing,
    clippy::string_slice,
    clippy::arithmetic_side_effects,
    clippy::let_underscore_must_use,
    clippy::as_conversions,
    clippy::cast_lossless
)]

#[rustfmt::skip]
#[allow(
    clippy::panic,
    clippy::unreachable,
    clippy::indexing_slicing,
    clippy::arithmetic_side_effects,
    clippy::as_conversions,
    clippy::let_underscore_must_use,
    reason = "generated by `wasm2rs --wit-host`: a `Host` method that is not overridden traps by design"
)]
#[expect(
    clippy::result_unit_err,
    reason = "the signatures are the WIT's: `result<_>` without an error type is `Result<_, ()>`"
)]
mod generated;

pub use generated::*;

mod host;

// Declared here, not in `host.rs`, so that the client stays a file of its own.
#[cfg(feature = "http-client")]
#[path = "host/ureq_client.rs"]
mod ureq_client;
#[cfg(feature = "http-client")]
pub use ureq_client::UreqClient;

#[cfg(feature = "os-random")]
pub use host::OsRandom;
pub use host::{
    Access, Clock, ConfigError, HttpClient, HttpClientError, HttpRequest, HttpResponse,
    IncomingRequestParts, InsecureRandom, NetworkPolicy, RandomError, RandomSource, ServedBody,
    ServedResponse, SystemClock, WasiHost, WasiHostBuilder,
};
